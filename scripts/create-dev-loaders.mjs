import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import { basename, dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(SCRIPT_DIR, '..');
const OUTPUT_DIR = join(ROOT, '.local');
const USER_SCRIPT_SUFFIX = '.user.js';

const filenames = (await readdir(ROOT))
  .filter(
    (filename) =>
      filename.endsWith(USER_SCRIPT_SUFFIX) &&
      !filename.toLowerCase().startsWith('dev-')
  )
  .sort();

if (!filenames.length) {
  throw new Error('No production userscripts were found in the repository root.');
}

await mkdir(OUTPUT_DIR, { recursive: true });

for (const filename of filenames) {
  const sourcePath = join(ROOT, filename);
  const source = await readFile(sourcePath, 'utf8');
  const metadata = extractMetadata(source, filename);
  const loader = createLoader(metadata, sourcePath);
  const loaderName = filename.replace(
    USER_SCRIPT_SUFFIX,
    `-loader${USER_SCRIPT_SUFFIX}`
  );

  await writeFile(join(OUTPUT_DIR, loaderName), loader, 'utf8');
  process.stdout.write(`Created .local/${loaderName}\n`);
}

function extractMetadata(source, filename) {
  const match = source.match(
    /^\/\/ ==UserScript==\r?\n[\s\S]*?^\/\/ ==\/UserScript==\s*$/m
  );

  if (!match) {
    throw new Error(`${filename} does not contain a valid userscript header.`);
  }

  return match[0].split(/\r?\n/);
}

function createLoader(metadataLines, sourcePath) {
  const output = [];
  let foundName = false;

  for (const line of metadataLines) {
    if (line === '// ==/UserScript==') {
      output.push(
        `// @require      ${pathToFileURL(sourcePath).href}`,
        line
      );
      continue;
    }

    if (/^\/\/ @(?:updateURL|downloadURL)\s+/.test(line)) {
      continue;
    }

    if (/^\/\/ @require\s+file:/i.test(line)) {
      continue;
    }

    const nameMatch = line.match(/^\/\/ @name\s+(.+)$/);
    if (nameMatch) {
      output.push(`// @name         DEV ${nameMatch[1].trim()}`);
      foundName = true;
      continue;
    }

    output.push(line);
  }

  if (!foundName) {
    throw new Error(
      `${basename(sourcePath)} does not declare a userscript @name.`
    );
  }

  return `${output.join('\n')}

// Generated by npm run dev:loaders.
// This loader intentionally has no script body; the local @require runs once.
`;
}
